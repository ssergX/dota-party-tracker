def _norm(text: str) -> str:
    """Регистр, «ё», пробелы, дефисы и апострофы не важны: «Анти-маг» == «антимаг»."""
    return re.sub(r"[^\w]", "", (text or "").lower().replace("ё", "е"))


def _build_index() -> dict[str, int]:
    index: dict[str, int] = {}
    for hid, name in HERO_NAMES.items():
        index[_norm(name)] = hid
    for hid, aliases in RU_ALIASES.items():
        for alias in aliases.split(","):
            index.setdefault(_norm(alias), hid)
    for alias, hid in _ALIASES.items():
        index[_norm(alias)] = hid
    return index


_INDEX = _build_index()
SUBSTRING_MIN = 4  # подстрока внутри слова — только от 4 символов: «od» не должен находить Bloodseeker


def update_heroes(data) -> int:
    """Дополнить/обновить справочник из ответа OpenDota /heroes ([{id, localized_name}]). Вернуть число новых."""
    global _INDEX
    added = 0
    for hero in data if isinstance(data, list) else []:
        try:
            hid, name = int(hero["id"]), hero["localized_name"]
        except (KeyError, TypeError, ValueError):
            continue
        if not isinstance(name, str) or not name:
            continue
        added += hid not in HERO_NAMES
        HERO_NAMES[hid] = name
    _INDEX = _build_index()
    return added


def find_hero(query: str):
    """Название героя (англ./рус./сленг: «морф», «моча», «джага») → hero_id | None.

    Порядок: точное совпадение (имя или алиас) → начало имени/алиаса → подстрока английского имени.
    """
    q = _norm(query)
    if not q:
        return None
    if q in _INDEX:
        return _INDEX[q]
    for key, hid in _INDEX.items():
        if key.startswith(q):
            return hid
    if len(q) >= SUBSTRING_MIN:
        for hid, name in HERO_NAMES.items():
            if q in _norm(name):
                return hid
    return None


def hero_name(hero_id) -> str:
    if not hero_id:
        return "?"
    return HERO_NAMES.get(hero_id, f"hero {hero_id}")
